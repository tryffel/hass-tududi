"""Bootstrap the local dev stack: tududi users/API keys/seed data and HA onboarding.

Idempotent: re-running reuses existing secrets in dev/.secrets.env and only seeds
data when tududi has no tasks. Use `make dev-reset` for a clean slate.

Run with: uv run --with aiohttp dev/bootstrap.py
"""

from __future__ import annotations

import asyncio
import json
import sys
from datetime import date, timedelta
from pathlib import Path

import aiohttp

TUDUDI = "http://localhost:3002"
HA = "http://localhost:8123"
SECRETS = Path(__file__).parent / ".secrets.env"
PASSWORD = "devpassword123"
CLIENT_ID = f"{HA}/"

USERS = {
    "giorgio": {"email": "giorgio@example.com", "name": "Giorgio"},
    "giulia": {"email": "giulia@example.com", "name": "Giulia"},
}


def log(msg: str) -> None:
    print(f"[bootstrap] {msg}", flush=True)


def load_secrets() -> dict[str, str]:
    if not SECRETS.exists():
        return {}
    out = {}
    for line in SECRETS.read_text().splitlines():
        if "=" in line and not line.startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def save_secrets(secrets: dict[str, str]) -> None:
    SECRETS.write_text(
        "# Generated by dev/bootstrap.py — local dev only\n"
        + "".join(f"{k}={v}\n" for k, v in sorted(secrets.items()))
    )


async def wait_for(session: aiohttp.ClientSession, url: str, name: str) -> None:
    for _ in range(120):
        try:
            async with session.get(url) as resp:
                if resp.status < 500:
                    log(f"{name} is up")
                    return
        except aiohttp.ClientError:
            pass
        await asyncio.sleep(2)
    sys.exit(f"{name} did not come up at {url}")


# --------------------------------------------------------------------------- tududi


async def tududi_login_key(email: str) -> str:
    """Log in with a session and create a personal API key."""
    jar = aiohttp.CookieJar(unsafe=True)
    async with aiohttp.ClientSession(cookie_jar=jar) as s:
        async with s.get(f"{TUDUDI}/api/csrf-token") as r:
            csrf = (await r.json())["csrfToken"]
        headers = {"x-csrf-token": csrf}
        async with s.post(
            f"{TUDUDI}/api/login",
            json={"email": email, "password": PASSWORD},
            headers=headers,
        ) as r:
            if r.status != 200:
                sys.exit(f"tududi login failed for {email}: {await r.text()}")
        async with s.post(
            f"{TUDUDI}/api/profile/api-keys",
            json={"name": "hass-dev"},
            headers=headers,
        ) as r:
            data = await r.json()
            return data["token"]


class Tududi:
    def __init__(self, session: aiohttp.ClientSession, key: str) -> None:
        self.s = session
        self.h = {"Authorization": f"Bearer {key}"}

    async def req(self, method: str, path: str, **kw):
        async with self.s.request(method, f"{TUDUDI}/api/v1{path}", headers=self.h, **kw) as r:
            if r.status >= 400:
                raise RuntimeError(f"{method} {path} -> {r.status}: {await r.text()}")
            return await r.json() if r.status != 204 else None

    async def valid(self) -> bool:
        try:
            await self.req("GET", "/profile")
            return True
        except RuntimeError:
            return False


async def setup_tududi(secrets: dict[str, str]) -> None:
    async with aiohttp.ClientSession() as s:
        await wait_for(s, f"{TUDUDI}/api/health", "tududi")

        giorgio_key = secrets.get("TUDUDI_GIORGIO_KEY")
        if not giorgio_key or not await Tududi(s, giorgio_key).valid():
            giorgio_key = await tududi_login_key(USERS["giorgio"]["email"])
            secrets["TUDUDI_GIORGIO_KEY"] = giorgio_key
            log("created API key for giorgio")
        giorgio = Tududi(s, giorgio_key)

        giulia_key = secrets.get("TUDUDI_GIULIA_KEY")
        if not giulia_key or not await Tududi(s, giulia_key).valid():
            try:
                await giorgio.req(
                    "POST",
                    "/admin/users",
                    json={
                        "email": USERS["giulia"]["email"],
                        "password": PASSWORD,
                        "name": USERS["giulia"]["name"],
                    },
                )
                log("created tududi user giulia")
            except RuntimeError as err:
                log(f"giulia user exists? ({err})")
            giulia_key = await tududi_login_key(USERS["giulia"]["email"])
            secrets["TUDUDI_GIULIA_KEY"] = giulia_key
            log("created API key for giulia")
        giulia = Tududi(s, giulia_key)

        save_secrets(secrets)
        await seed_tududi(giorgio, giulia)


async def seed_tududi(giorgio: Tududi, giulia: Tududi) -> None:
    existing = await giorgio.req("GET", "/tasks", params={"type": "all", "status": "all"})
    if existing.get("tasks"):
        log("tududi already seeded, skipping")
        return

    today = date.today()

    def due(days: int) -> str:
        return (today + timedelta(days=days)).isoformat()

    await giorgio.req("PATCH", "/profile", json={"name": "Giorgio", "timezone": "Europe/Helsinki"})
    await giulia.req("PATCH", "/profile", json={"name": "Giulia", "timezone": "Europe/Helsinki"})

    bills = await giorgio.req("POST", "/project", json={"name": "Household bills"})
    await giorgio.req(
        "POST",
        "/shares",
        json={
            "resource_type": "project",
            "resource_uid": bills["uid"],
            "target_user_email": USERS["giulia"]["email"],
            "access_level": "rw",
        },
    )
    invitations = await giulia.req("GET", "/shares/invitations")
    for inv in invitations.get("invitations", []):
        await giulia.req("POST", f"/shares/invitations/{inv['id']}/accept")
    devices = await giorgio.req("POST", "/project", json={"name": "Devices"})

    people = await giorgio.req("GET", "/people")
    people_list = people if isinstance(people, list) else people.get("people", [])
    giulia_person = next(
        (p for p in people_list if p.get("linked_user_id") and p.get("name") == "Giulia"),
        None,
    )

    invoices = [
        ("Electricity invoice", -1, "Amount 52.10 EUR\nRef 1234 5678", None),
        ("Water invoice", 0, "Amount 31.00 EUR", None),
        ("Internet invoice", 3, "Amount 29.90 EUR", "giulia"),
        ("Insurance invoice", 7, "Amount 210.00 EUR", None),
        ("Daycare invoice", 10, "Amount 300.00 EUR", "giulia"),
    ]
    for name, days, note, assignee in invoices:
        body = {
            "name": name,
            "due_date": due(days),
            "note": note,
            "project_uid": bills["uid"],
            "tags": [{"name": "invoice"}],
            "priority": 1,
        }
        if assignee == "giulia" and giulia_person:
            body["assigned_to"] = giulia_person["uid"]
        await giorgio.req("POST", "/task", json=body)

    await giorgio.req(
        "POST",
        "/task",
        json={
            "name": "Old paid invoice",
            "due_date": due(-5),
            "status": 2,
            "project_uid": bills["uid"],
            "tags": [{"name": "invoice"}],
        },
    )
    await giorgio.req("POST", "/task", json={"name": "Fix bike tyre", "due_date": due(2)})
    await giorgio.req("POST", "/task", json={"name": "Buy coffee", "priority": 2})
    await giorgio.req(
        "POST",
        "/task",
        json={
            "name": "Replace battery: Hallway motion sensor",
            "project_uid": devices["uid"],
            "tags": [{"name": "battery"}],
            "note": "ha:battery:sensor.hallway_motion_battery",
        },
    )
    await giulia.req("POST", "/task", json={"name": "Book dentist", "due_date": due(5)})

    await giorgio.req(
        "POST",
        "/note",
        json={
            "title": "Hallway motion sensor",
            "project_uid": devices["uid"],
            "content": "Battery: CR2032\n\n- 2026-03-02 replaced",
        },
    )
    await giorgio.req(
        "POST",
        "/note",
        json={
            "title": "Bills info",
            "project_uid": bills["uid"],
            "content": "Electricity contract renews in January.",
        },
    )
    log("seeded tududi data")


# --------------------------------------------------------------------------- Home Assistant


async def ha_token_from_code(s: aiohttp.ClientSession, code: str) -> str:
    async with s.post(
        f"{HA}/auth/token",
        data={"grant_type": "authorization_code", "code": code, "client_id": CLIENT_ID},
    ) as r:
        return (await r.json())["access_token"]


async def ha_login(s: aiohttp.ClientSession, username: str) -> str:
    async with s.post(
        f"{HA}/auth/login_flow",
        json={"client_id": CLIENT_ID, "handler": ["homeassistant", None], "redirect_uri": f"{HA}/"},
    ) as r:
        flow = await r.json()
    async with s.post(
        f"{HA}/auth/login_flow/{flow['flow_id']}",
        json={"client_id": CLIENT_ID, "username": username, "password": PASSWORD},
    ) as r:
        result = await r.json()
    return await ha_token_from_code(s, result["result"])


class HAWs:
    def __init__(self, ws: aiohttp.ClientWebSocketResponse) -> None:
        self.ws = ws
        self.id = 0

    async def call(self, msg_type: str, **data):
        self.id += 1
        await self.ws.send_json({"id": self.id, "type": msg_type, **data})
        while True:
            msg = await self.ws.receive_json()
            if msg.get("id") == self.id and msg.get("type") == "result":
                if not msg["success"]:
                    raise RuntimeError(f"{msg_type}: {msg['error']}")
                return msg["result"]


async def ha_ws(s: aiohttp.ClientSession, token: str) -> HAWs:
    ws = await s.ws_connect(f"{HA}/api/websocket")
    await ws.receive_json()
    await ws.send_json({"type": "auth", "access_token": token})
    auth = await ws.receive_json()
    if auth["type"] != "auth_ok":
        sys.exit(f"HA websocket auth failed: {auth}")
    return HAWs(ws)


async def setup_ha(secrets: dict[str, str]) -> None:
    async with aiohttp.ClientSession() as s:
        await wait_for(s, f"{HA}/api/onboarding", "Home Assistant")
        async with s.get(f"{HA}/api/onboarding") as r:
            # 404 once onboarding has been completed.
            steps = {st["step"]: st["done"] for st in await r.json()} if r.status == 200 else {}
        if r.status == 404:
            steps = dict.fromkeys(("user", "core_config", "analytics", "integration"), True)

        if not steps.get("user"):
            async with s.post(
                f"{HA}/api/onboarding/users",
                json={
                    "client_id": CLIENT_ID,
                    "name": "Giorgio",
                    "username": "giorgio",
                    "password": PASSWORD,
                    "language": "en",
                },
            ) as r:
                code = (await r.json())["auth_code"]
            token = await ha_token_from_code(s, code)
            log("HA owner user created")
        else:
            token = await ha_login(s, "giorgio")

        auth = {"Authorization": f"Bearer {token}"}
        for step, body in (
            ("core_config", {}),
            ("analytics", {}),
            ("integration", {"client_id": CLIENT_ID, "redirect_uri": f"{HA}/"}),
        ):
            if not steps.get(step):
                async with s.post(f"{HA}/api/onboarding/{step}", json=body, headers=auth) as r:
                    if r.status >= 400:
                        log(f"onboarding {step}: {r.status} {await r.text()}")

        ws = await ha_ws(s, token)
        await ws.call(
            "config/core/update",
            time_zone="Europe/Helsinki",
            country="FI",
            currency="EUR",
            unit_system="metric",
        )

        users = await ws.call("config/auth/list")
        if not any(u["name"] == "Giulia" for u in users):
            user = await ws.call("config/auth/create", name="Giulia", group_ids=["system-users"])
            await ws.call(
                "config/auth_provider/homeassistant/create",
                user_id=user["user"]["id"],
                username="giulia",
                password=PASSWORD,
            )
            log("HA user giulia created")

        if not secrets.get("HA_TOKEN"):
            secrets["HA_TOKEN"] = await ws.call(
                "auth/long_lived_access_token", client_name="hass-tududi-dev", lifespan=3650
            )
            log("HA long-lived token created")
        ha_users = {u["name"]: u["id"] for u in await ws.call("config/auth/list")}
        await ws.ws.close()

        await setup_ha_entries(s, auth, secrets, ha_users)

    save_secrets(secrets)


# tududi as seen from inside the docker network.
TUDUDI_INTERNAL = "http://tududi:3002"


async def setup_ha_entries(
    s: aiohttp.ClientSession,
    auth: dict[str, str],
    secrets: dict[str, str],
    ha_users: dict[str, str],
) -> None:
    """Add one tududi config entry per dev user through the real config flow."""
    flows = f"{HA}/api/config/config_entries"
    async with s.get(f"{flows}/entry", params={"domain": "tududi"}, headers=auth) as r:
        existing = {e["title"] for e in await r.json()}

    for user, info in USERS.items():
        name = info["name"]
        if name in existing:
            continue
        async with s.post(f"{flows}/flow", json={"handler": "tududi"}, headers=auth) as r:
            flow = await r.json()
            if "flow_id" not in flow:
                log(f"cannot start tududi config flow (is the integration loaded?): {flow}")
                return
        async with s.post(
            f"{flows}/flow/{flow['flow_id']}",
            json={
                "url": TUDUDI_INTERNAL,
                "api_key": secrets[f"TUDUDI_{user.upper()}_KEY"],
                "verify_ssl": True,
            },
            headers=auth,
        ) as r:
            result = await r.json()
        if result.get("type") != "create_entry":
            log(f"config flow for {name} did not finish: {result}")
            continue
        entry_id = result["result"]["entry_id"]
        log(f"HA config entry added for {name}")

        async with s.post(f"{flows}/options/flow", json={"handler": entry_id}, headers=auth) as r:
            options = await r.json()
        async with s.post(
            f"{flows}/options/flow/{options['flow_id']}",
            json={
                "ha_user": ha_users[name],
                "update_interval": 60,
                "default_notify": f"notify.test_{user}",
                "reminders_enabled": True,
                "reminder_tag": "invoice",
                "reminder_days_before": 7,
                "reminder_time": "09:00:00",
                "reminder_include_overdue": True,
            },
            headers=auth,
        ) as r:
            step = await r.json()
        if step.get("step_id") == "notify":
            # Map the other household member's tududi person to their test target.
            mapping = {
                other["name"]: f"notify.test_{other_user}"
                for other_user, other in USERS.items()
                if other_user != user
            }
            async with s.post(
                f"{flows}/options/flow/{options['flow_id']}", json=mapping, headers=auth
            ) as r:
                step = await r.json()
        if step.get("type") != "create_entry":
            log(f"options flow for {name} did not finish: {step}")


async def main() -> None:
    secrets = load_secrets()
    await setup_tududi(secrets)
    await setup_ha(secrets)
    log("done")
    log(f"tududi: {TUDUDI}  (giorgio@example.com / giulia@example.com, password {PASSWORD})")
    log(f"Home Assistant: {HA}  (giorgio / giulia, password {PASSWORD})")
    log(f"secrets: {SECRETS}")
    print(json.dumps({"ok": True}))


if __name__ == "__main__":
    asyncio.run(main())
